<?php

declare(strict_types=1);

/**
 * CLI: write config/config.php for a new install (used by install/install.sh).
 *
 * Usage: php bin/setup-config.php --public-url=https://sentinel.msp.example [--db-host=127.0.0.1]
 *            [--db-name=msp_sentinel] [--db-user=msp_sentinel] [--config=PATH] [--trusted-proxy=IP]
 *            (database password on stdin; --trusted-proxy: the reverse proxy whose X-Forwarded-* headers are trusted)
 *
 * Starts from config/config.example.php, sets a fresh random app key, the
 * database details and the public address, and writes the file with mode 0640.
 *
 * Security assumptions: run by the installer as root. The database password
 * is read from stdin (never the command line, which other users can see).
 * It refuses to overwrite an existing config (that would lose the app key).
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

$root = dirname(__DIR__);
$opts = getopt('', ['public-url:', 'db-host:', 'db-name:', 'db-user:', 'config:', 'trusted-proxy:']);
$proxy = (string) ($opts['trusted-proxy'] ?? '');
if ($proxy !== '' && filter_var($proxy, FILTER_VALIDATE_IP) === false) {
    fwrite(STDERR, "--trusted-proxy must be one IP address.\n");
    exit(2);
}
$target = is_string($opts['config'] ?? null) ? $opts['config'] : $root . '/config/config.php';
$url = (string) ($opts['public-url'] ?? '');
$name = (string) ($opts['db-name'] ?? 'msp_sentinel');
$user = (string) ($opts['db-user'] ?? 'msp_sentinel');
$host = (string) ($opts['db-host'] ?? '127.0.0.1');
if (!preg_match('#^https://[a-z0-9.-]+(:\d{1,5})?$#i', $url)) {
    fwrite(STDERR, "--public-url must look like https://sentinel.msp.example\n");
    exit(2);
}
if (!preg_match('/^[A-Za-z0-9_]{1,64}$/', $name) || !preg_match('/^[A-Za-z0-9_]{1,32}$/', $user) || !preg_match('/^[A-Za-z0-9.:-]{1,253}$/', $host)) {
    fwrite(STDERR, "Invalid database name, user or host.\n");
    exit(2);
}
if (file_exists($target)) {
    fwrite(STDERR, "{$target} already exists; not overwriting it (it holds the app key).\n");
    exit(1);
}
$password = rtrim((string) fgets(STDIN), "\r\n");
if ($password === '') {
    fwrite(STDERR, "Send the database password on stdin.\n");
    exit(2);
}
$cfg = require $root . '/config/config.example.php';
$cfg['app_key'] = base64_encode(random_bytes(32));
$cfg['db'] = ['host' => $host, 'port' => 3306, 'name' => $name, 'user' => $user, 'pass' => $password];
$cfg['app']['public_url'] = rtrim($url, '/');
$cfg['app']['force_secure_cookies'] = true;
if ($proxy !== '') {
    $cfg['app']['trusted_proxies'] = [inet_ntop((string) inet_pton($proxy))]; // only this proxy's X-Forwarded-* headers count
}
$php = "<?php\n\n// Generated by bin/setup-config.php on " . gmdate('Y-m-d') . ". Keep this file private and back it up:\n"
    . "// its app_key encrypts 2FA seeds and saved secrets. See docs/configuration.md for every option.\n\nreturn " . var_export($cfg, true) . ";\n";
$old = umask(0027);
$ok = file_put_contents($target, $php, LOCK_EX);
umask($old);
if ($ok === false) {
    fwrite(STDERR, "Could not write {$target}.\n");
    exit(1);
}
chmod($target, 0640);
fwrite(STDOUT, "Wrote {$target}\n");
